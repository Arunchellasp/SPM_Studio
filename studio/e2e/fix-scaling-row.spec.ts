/** Found on the PC (physical test P-20.4): REG → AI, then the last problem 'needs scale' had no Change… to fix it. */
import { expect, test, type Locator, type Page } from '@playwright/test'

const row = (page: Page, name: string): Locator =>
  page.locator('.tabulator-row').filter({ has: page.locator('.tabulator-cell[tabulator-field="name"]', { hasText: new RegExp(`^(⚠ )?${name}$`) }) })
const cell = (page: Page, name: string, field: string): Locator => row(page, name).locator(`.tabulator-cell[tabulator-field="${field}"]`)
const problems = (page: Page): Locator => page.getByTestId('project-problems')
const editor = (page: Page): Locator => page.locator('.tabulator-cell.tabulator-editing input')

test('UI-F2 REG → AI, then name, unit, address and scaling fixed one by one; at 0 problems Save works', async ({ page }) => {
  await page.goto('/')
  await page.locator('.rail-item', { hasText: 'Tags' }).click()
  await page.getByRole('button', { name: 'Open project…' }).click()
  await row(page, 'R_S1_Step').click()
  await page.locator('.tgs-details').getByLabel('Kind').selectOption('AI')
  await page.getByRole('alertdialog').getByRole('button', { name: 'Change to AI' }).click()
  await expect(problems(page)).toHaveText('⚠ 4 problems')
  await cell(page, 'R_S1_Step', 'name').dblclick()
  await editor(page).fill('AI_S1_Step')
  await editor(page).press('Enter')
  await expect(problems(page)).toHaveText('⚠ 3 problems')
  await cell(page, 'AI_S1_Step', 'unit').dblclick()
  await editor(page).fill('degC')
  await editor(page).press('Enter')
  await expect(problems(page)).toHaveText('⚠ 2 problems')
  await page.getByRole('button', { name: 'Change address…' }).click()
  const ad = page.getByRole('dialog', { name: 'Address · AI_S1_Step' })
  await ad.getByLabel('Slave').fill('5')
  await ad.getByLabel('Channel').fill('2')
  await ad.getByRole('button', { name: 'OK' }).click()
  await expect(problems(page)).toHaveText('⚠ 1 problem')
  await expect(page.locator('.tgs-details')).toContainText('– (none yet)')
  await page.getByRole('button', { name: 'Change scaling…' }).click()
  await page.getByRole('dialog', { name: 'Scaling · AI_S1_Step' }).getByRole('button', { name: 'OK' }).click()
  await expect(problems(page)).toHaveCount(0)
  await expect(cell(page, 'AI_S1_Step', 'unit')).not.toHaveClass(/cell-bad/)
  await page.getByRole('button', { name: 'Save' }).click()
  await expect(page.getByRole('status').last()).toContainText('Saved')
})
